import assert from 'node:assert/strict';
import {createRegistry,localModuleURL,assertActor} from './registry.mjs';
import {register,summarizeChanges} from '../extensions/duration.mjs';
import {toCanvasDocument,fromCanvasDocument,readback} from '../model.mjs';

const registry=createRegistry();
register(registry);
assert.equal(registry.commands.get('demo:add-cue').placement,'toolbar');
const cue=registry.create('demo:cue',{id:'cue',parentId:'frame'});
assert.equal(cue.data.durationSeconds,2);
assert.throws(()=>registry.create('demo:cue',{id:'bad',data:{durationSeconds:-1}}),/nonnegative/);
assert.equal(registry.types.get('demo:cue').inspector[0].key,'durationSeconds');
const frame={id:'frame',type:'core:frame',geometry:{x:0,y:0,w:800,h:500},data:{label:'Test'}};
const opaque={id:'opaque',type:'unavailable:widget',parentId:'frame',geometry:{x:4,y:8,w:90,h:70},data:{label:'Unknown',nested:{unit:'beats',value:3}},source:{kind:'seed'},vendorField:{preserve:true}};
const baseline=[frame,cue,opaque];
const document={schemaVersion:2,revision:0,title:'Extension contract',objects:structuredClone(baseline),baseline:structuredClone(baseline),notes:[{id:'note',targetId:'opaque',text:'Keep this unknown object'}],events:[]};
const view=toCanvasDocument(document);
const projectedCue=view.frames[0].pieces.find(o=>o.id==='cue');
assert.equal(projectedCue.registeredType,'demo:cue');
projectedCue.extensionData.durationSeconds=4.5;
view.events.push({id:'event',type:'edit-domain-field',actor:'user',changes:[{targetId:'cue'}]});
const result=fromCanvasDocument(view,document);
assert.deepEqual(result.objects.find(o=>o.id==='opaque'),opaque);
assert.deepEqual(result.notes,document.notes);
const feedback=readback(result,[{summarizeChanges}]);
const cueFeedback=feedback.changes.find(o=>o.targetId==='cue');
assert.equal(cueFeedback.semantic[0].text,'Duration changed from 2s to 4.5s');
assert.equal(cueFeedback.events[0].actor,'user');
assert.equal(feedback.changes.some(o=>o.targetId==='opaque'),false);
assert.equal(localModuleURL('extensions/duration.mjs','http://127.0.0.1:5320/toolkit/canvas/index.html'),'http://127.0.0.1:5320/extensions/duration.mjs');
for(const bad of ['https://remote.example/a.mjs','//remote.example/a.mjs','../escape.mjs','extensions/a.js','extensions/a.mjs?q=1'])assert.throws(()=>localModuleURL(bad,'http://127.0.0.1:5320/'));
for(const actor of ['user','agent','verification'])assert.equal(assertActor(actor),actor);
assert.throws(()=>assertActor('implicit'));
registry.registerType('example:nonspatial',{defaults:{data:{label:'Domain node'}}});
assert.equal(registry.create('example:nonspatial',{id:'n'}).geometry,undefined);
console.log('PASS: duration field validation/semantic readback, actor evidence, unknown-data roundtrip, local-only extension paths, optional geometry.');
